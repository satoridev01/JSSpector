//! OpenAPI 3.1 export of the HTTP entry points.

use std::collections::BTreeMap;

use jss_frontend::Route;
use serde_json::{Map, Value, json};

/// HTTP methods OpenAPI has operations for.
const METHODS: &[&str] = &[
    "get", "put", "post", "delete", "options", "head", "patch", "trace",
];

/// An OpenAPI 3.1 document of `routes` (HTTP only). Routes registered for any method (`ALL`,
/// `ANY`, `USE`) are listed under every method they may answer, marked `x-jsspector-any-method`.
pub fn document(title: &str, routes: &[Route]) -> Value {
    let mut paths: BTreeMap<String, Map<String, Value>> = BTreeMap::new();
    for route in routes.iter().filter(|r| r.kind == "http") {
        let method = route.method.to_ascii_lowercase();
        let methods: Vec<&str> = if METHODS.contains(&method.as_str()) {
            vec![
                METHOD_NAMES
                    .iter()
                    .copied()
                    .find(|m| *m == method)
                    .unwrap_or("get"),
            ]
        } else {
            vec!["get", "post"]
        };
        for method in methods {
            let operations = paths.entry(route.path.clone()).or_default();
            operations.insert(method.to_owned(), operation(route, method));
        }
    }
    json!({
        "openapi": "3.1.0",
        "info": { "title": title, "version": "0.0.0", "description": "Generated by jsspector from source code (static analysis)." },
        "paths": paths,
    })
}

const METHOD_NAMES: &[&str] = METHODS;

fn operation(route: &Route, method: &str) -> Value {
    let mut parameters: Vec<Value> = route
        .path
        .split('/')
        .filter_map(|s| s.strip_prefix('{').and_then(|s| s.strip_suffix('}')))
        .map(|name| json!({ "name": name, "in": "path", "required": true, "schema": { "type": "string" } }))
        .collect();
    let mut body = Map::new();
    for input in &route.inputs {
        let Some((location, name)) = input.split_once('.') else {
            continue;
        };
        match location {
            "query" => parameters
                .push(json!({ "name": name, "in": "query", "schema": { "type": "string" } })),
            "headers" => parameters
                .push(json!({ "name": name, "in": "header", "schema": { "type": "string" } })),
            "cookies" => parameters
                .push(json!({ "name": name, "in": "cookie", "schema": { "type": "string" } })),
            "body" | "payload" => {
                body.insert(name.to_owned(), json!({}));
            }
            _ => {}
        }
    }
    let mut op = json!({
        "operationId": format!("{method}_{}", route.handler.replace([' ', '/', ':', '{', '}', '.'], "_")),
        "parameters": parameters,
        "responses": { "default": { "description": "Not modeled" } },
        "x-jsspector-handler": route.handler,
        "x-jsspector-source": format!("{}:{}", route.file, route.line),
        "x-jsspector-auth": route.auth.name(),
    });
    if !METHODS.contains(&route.method.to_ascii_lowercase().as_str())
        && let Some(map) = op.as_object_mut()
    {
        map.insert("x-jsspector-any-method".to_owned(), json!(route.method));
    }
    if !body.is_empty()
        && let Some(map) = op.as_object_mut()
    {
        map.insert(
            "requestBody".to_owned(),
            json!({ "content": { "application/json": { "schema": { "type": "object", "properties": body } } } }),
        );
    }
    op
}
