//! End-to-end tests of `jsspector parse` on a temporary tree.

// Test-only crate: failing loudly is the point. (clippy.toml's `allow-*-in-tests` settings do
// not reach the helper functions of an integration-test crate.)
#![allow(
    clippy::unwrap_used,
    clippy::expect_used,
    clippy::panic,
    clippy::indexing_slicing
)]

use std::fs;
use std::path::{Path, PathBuf};
use std::process::{Command, Output};

use serde_json::{Value, json};

fn jsspector(args: &[&str]) -> Output {
    Command::new(env!("CARGO_BIN_EXE_jsspector"))
        .args(args)
        .env_remove("RAYON_NUM_THREADS")
        .output()
        .unwrap()
}

/// Runs a command expected to succeed quietly; returns the parsed report and its exact text.
fn report(args: &[&str]) -> (Value, String) {
    let output = jsspector(args);
    let stderr = String::from_utf8_lossy(&output.stderr);
    assert_eq!(output.status.code(), Some(0), "{args:?}: {stderr}");
    assert!(stderr.is_empty(), "stderr must stay quiet: {stderr}");
    let stdout = String::from_utf8(output.stdout).unwrap();
    (serde_json::from_str(&stdout).unwrap(), stdout)
}

fn write(root: &Path, rel: &str, contents: impl AsRef<[u8]>) {
    let path = root.join(rel);
    fs::create_dir_all(path.parent().unwrap()).unwrap();
    fs::write(path, contents).unwrap();
}

struct Fixture {
    _dir: tempfile::TempDir,
    root: PathBuf,
}

impl Fixture {
    fn root(&self) -> &str {
        self.root.to_str().unwrap()
    }

    fn file(&self, rel: &str) -> String {
        self.root.join(rel).to_str().unwrap().to_owned()
    }
}

/// HTML-like comments: legal in a CommonJS script, a recoverable error in an ES module.
const LEGACY: &str = "<!-- legacy HTML-like comment\nlegacy();\n";

fn fixture() -> Fixture {
    let dir = tempfile::tempdir().unwrap();
    let root = dir.path().join("repo");
    write(
        &root,
        "package.json",
        r#"{"name": "fixture", "private": true}"#,
    );
    // Never discovered: ignored by .gitignore, hidden, or a declaration file.
    write(&root, ".gitignore", "ignored/\n");
    write(&root, "ignored/skip.js", "skip();\n");
    write(&root, ".cache/hidden.js", "hidden();\n");
    write(&root, "src/types.d.ts", "export type T = string;\n");
    // Source: JSX in a .js file, TypeScript decorators, and files every check must catch.
    write(
        &root,
        "src/app.js",
        "const App = () => <div onClick={go}>hi</div>;\nmodule.exports = App;\n",
    );
    write(
        &root,
        "src/users.controller.ts",
        "@Controller('users')\nexport class UsersController {\n  @Get(':id')\n  \
         find(@Param('id') id: string): string {\n    return id;\n  }\n}\n",
    );
    write(&root, "src/legacy.js", LEGACY);
    write(&root, "src/broken.js", "const x = ;\n");
    write(
        &root,
        "src/packed.js",
        format!("var a=[{}];\n", "1,".repeat(15_000)),
    );
    write(&root, "src/latin1.js", b"var s = '\xe9t\xe9';\n");
    write(
        &root,
        "src/deep.js",
        format!("x =\n{}1{};\n", "(\n".repeat(2_500), "\n)".repeat(2_500)),
    );
    write(
        &root,
        "src/schema.ts",
        "// @generated by a code generator\nexport const schema = {};\n",
    );
    // Flow-typed JavaScript parses with TypeScript syntax.
    write(
        &root,
        "src/flow.js",
        "// @flow\nimport type { A } from './a';\nexport const f = (x: A): A => x;\n",
    );
    // An EJS template with a .js extension is not JavaScript.
    write(
        &root,
        "src/templates/page.js",
        "window.vars = { prefix: <%- JSON.stringify(prefix) %> };\n",
    );
    // Real code under names the classifier must not misread: a capitalized `Docs` directory and
    // a `build` feature inside a source tree. A long string literal is not minified code.
    write(
        &root,
        "src/nodes/Google/Docs/GoogleDocs.node.ts",
        "export class GoogleDocs {}\n",
    );
    write(
        &root,
        "src/build/app-build.controller.ts",
        "export class AppBuildController {}\n",
    );
    write(
        &root,
        "src/logo.ts",
        format!(
            "export const logo = {{\n  src: 'data:image/png;base64,{}',\n}};\n",
            "A".repeat(30_000)
        ),
    );
    // Vendored code (inside a source tree) and test-runner configuration.
    write(
        &root,
        "src/static/thirdparty/jquery.js",
        "jQuery = function () {};\n",
    );
    write(&root, "vitest.config.ts", "export default {};\n");
    // A nested package with "type": "module".
    write(&root, "esm/package.json", r#"{"type": "module"}"#);
    write(
        &root,
        "esm/index.js",
        "import { a } from './a.js';\nexport default a;\n",
    );
    write(&root, "esm/legacy.js", LEGACY);
    // Not source.
    write(&root, "test/app.test.js", "test('app', () => {});\n");
    write(&root, "node_modules/lib/index.js", "module.exports = 1;\n");
    write(&root, "dist/bundle.js", "bundled();\n");
    write(&root, "docs/guide.js", "guide();\n");
    write(&root, "examples/demo.js", "demo();\n");
    #[cfg(unix)]
    {
        use std::os::unix::fs::symlink;
        write(dir.path(), "outside/secret.js", "steal();\n");
        symlink(
            dir.path().join("outside/secret.js"),
            root.join("src/escape.js"),
        )
        .unwrap();
        // The same file as src/app.js: listed once, under its real path, as source, even
        // though a docs link to it sorts first.
        symlink("app.js", root.join("src/zlink.js")).unwrap();
        fs::create_dir_all(root.join("docs/snippets")).unwrap();
        symlink("../../src/app.js", root.join("docs/snippets/app.js")).unwrap();
    }
    Fixture { _dir: dir, root }
}

fn str_of<'a>(value: &'a Value, key: &str) -> &'a str {
    value[key]
        .as_str()
        .unwrap_or_else(|| panic!("{key} in {value}"))
}

#[test]
fn reports_classes_skips_and_diagnostics() {
    let fixture = fixture();
    let (report, _) = report(&["parse", fixture.root(), "--list"]);
    assert_eq!(report["schema"], "jsspector.parse-report/1");
    assert_eq!(report["root"], fixture.root());
    assert!(report.get("stats").is_none(), "stats only with --stats");

    assert_eq!(report["selection"], json!(["source"]));
    let symlink_skips = usize::from(cfg!(unix));
    assert_eq!(
        report["totals"],
        json!({
            "files": 22,
            "by_class": {"docs": 1, "example": 1, "generated": 2, "source": 14, "test": 2, "vendor": 2},
            "declaration_files": 1,
            "selected": 14,
            "parsed_ok": 8,
            "recovered": 1,
            "fatal": 1,
            "panicked": 0,
            "skipped": 4,
            "skipped_by_reason": {
                "io-error": 0,
                "minified": 1,
                "not-utf8": 1,
                "symlink-outside-root": 0,
                "template": 1,
                "too-deep": 1,
                "too-large": 0
            },
            "flow": 1,
            "discovery_skips_by_reason": {
                "io-error": 0,
                "minified": 0,
                "not-utf8": 0,
                "symlink-outside-root": symlink_skips,
                "template": 0,
                "too-deep": 0,
                "too-large": 0
            }
        })
    );

    let mut expected = vec![
        (
            "esm/legacy.js",
            "parse/recovered",
            "1:1: HTML comments are not allowed in modules",
        ),
        ("src/broken.js", "parse/fatal", "1:11: Unexpected token"),
        (
            "src/deep.js",
            "skip/too-deep",
            "bracket nesting depth 2500 exceeds the limit of 2000",
        ),
    ];
    if cfg!(unix) {
        expected.push((
            "src/escape.js",
            "skip/symlink-outside-root",
            "symlink resolves outside the scan root; not followed",
        ));
    }
    expected.extend([
        (
            "src/latin1.js",
            "skip/not-utf8",
            "invalid UTF-8 at byte offset 9",
        ),
        (
            "src/packed.js",
            "skip/minified",
            "line 1 is 30009 characters long, not counting string literals (limit 20000)",
        ),
        (
            "src/templates/page.js",
            "skip/template",
            "1:25: template tag `<%` (a server-side template such as EJS, not JavaScript)",
        ),
    ]);
    let diagnostics: Vec<(&str, &str, &str)> = report["diagnostics"]
        .as_array()
        .unwrap()
        .iter()
        .map(|d| (str_of(d, "path"), str_of(d, "code"), str_of(d, "message")))
        .collect();
    assert_eq!(diagnostics, expected);

    let files = report["files"].as_array().unwrap();
    let summary: Vec<(&str, &str, &str, &str)> = files
        .iter()
        .map(|f| {
            (
                str_of(f, "path"),
                str_of(f, "class"),
                str_of(f, "package_type"),
                str_of(f, "status"),
            )
        })
        .collect();
    assert_eq!(
        summary,
        [
            ("dist/bundle.js", "generated", "commonjs", "excluded"),
            ("docs/guide.js", "docs", "commonjs", "excluded"),
            ("esm/index.js", "source", "module", "parsed"),
            ("esm/legacy.js", "source", "module", "recovered"),
            ("examples/demo.js", "example", "commonjs", "excluded"),
            (
                "node_modules/lib/index.js",
                "vendor",
                "commonjs",
                "excluded"
            ),
            ("src/app.js", "source", "commonjs", "parsed"),
            ("src/broken.js", "source", "commonjs", "fatal"),
            (
                "src/build/app-build.controller.ts",
                "source",
                "commonjs",
                "parsed"
            ),
            ("src/deep.js", "source", "commonjs", "skipped"),
            ("src/flow.js", "source", "commonjs", "parsed"),
            ("src/latin1.js", "source", "commonjs", "skipped"),
            ("src/legacy.js", "source", "commonjs", "parsed"),
            ("src/logo.ts", "source", "commonjs", "parsed"),
            (
                "src/nodes/Google/Docs/GoogleDocs.node.ts",
                "source",
                "commonjs",
                "parsed"
            ),
            ("src/packed.js", "source", "commonjs", "skipped"),
            ("src/schema.ts", "generated", "commonjs", "excluded"),
            (
                "src/static/thirdparty/jquery.js",
                "vendor",
                "commonjs",
                "excluded"
            ),
            ("src/templates/page.js", "source", "commonjs", "skipped"),
            ("src/users.controller.ts", "source", "commonjs", "parsed"),
            ("test/app.test.js", "test", "commonjs", "excluded"),
            ("vitest.config.ts", "test", "commonjs", "excluded"),
        ]
    );
    let record = |path: &str| files.iter().find(|f| f["path"] == path).unwrap();
    assert_eq!(
        record("src/app.js"),
        &json!({
            "path": "src/app.js",
            "class": "source",
            "package_type": "commonjs",
            "size": 68,
            "status": "parsed",
            "statements": 2,
            "syntax_errors": 0
        })
    );
    assert_eq!(record("src/users.controller.ts")["syntax_errors"], 0);
    assert_eq!(record("esm/legacy.js")["syntax_errors"], 1);
    assert_eq!(record("src/deep.js")["reason"], "too-deep");
    assert_eq!(record("src/latin1.js")["reason"], "not-utf8");
    assert_eq!(record("src/packed.js")["reason"], "minified");
    assert_eq!(record("src/templates/page.js")["reason"], "template");
    assert_eq!(record("src/flow.js")["flow"], true);
    assert!(record("src/app.js").get("flow").is_none(), "only when true");
    assert_eq!(
        record("test/app.test.js"),
        &json!({
            "path": "test/app.test.js",
            "class": "test",
            "package_type": "commonjs",
            "size": 23,
            "status": "excluded"
        })
    );
}

#[test]
fn include_adds_classes_to_the_selection() {
    let fixture = fixture();
    let (tests, _) = report(&["parse", fixture.root(), "--include", "tests,examples"]);
    assert_eq!(tests["selection"], json!(["source", "example", "test"]));
    assert_eq!(tests["totals"]["selected"], 17);
    assert_eq!(tests["totals"]["parsed_ok"], 11);
    let (all, _) = report(&["parse", fixture.root(), "--include", "all"]);
    assert_eq!(all["totals"]["selected"], 22);
    assert_eq!(all["totals"]["parsed_ok"], 16);
    // Final classes (the @generated marker included) do not depend on the selection.
    let (default, _) = report(&["parse", fixture.root()]);
    assert_eq!(all["totals"]["by_class"], tests["totals"]["by_class"]);
    assert_eq!(all["totals"]["by_class"], default["totals"]["by_class"]);
}

#[test]
fn report_is_byte_identical_for_any_thread_count() {
    let fixture = fixture();
    let (_, one) = report(&["parse", fixture.root(), "--list", "--threads", "1"]);
    let (_, four) = report(&["parse", fixture.root(), "--list", "--threads", "4"]);
    assert_eq!(one, four);
    let (_, default_threads) = report(&["parse", fixture.root(), "--list"]);
    assert_eq!(one, default_threads);

    // --stats only appends the (non-deterministic) stats object.
    for threads in ["1", "4"] {
        let (with_stats, text) = report(&[
            "parse",
            fixture.root(),
            "--list",
            "--threads",
            threads,
            "--stats",
        ]);
        let (deterministic, _) = text
            .rsplit_once(",\n  \"stats\": ")
            .expect("stats is the last field");
        assert_eq!(format!("{deterministic}\n}}\n"), one);
        let stats = &with_stats["stats"];
        assert_eq!(stats["threads"].to_string(), threads);
        for phase in ["discover", "parse", "total"] {
            assert!(stats["wall_ms"][phase].as_f64().unwrap() >= 0.0, "{stats}");
        }
        assert!(stats["files_per_sec"].as_f64().unwrap() >= 0.0);
        assert!(stats["bytes_per_sec"].as_f64().unwrap() >= 0.0);
        if cfg!(unix) {
            assert!(stats["peak_rss_bytes"].as_u64().unwrap() > 1024 * 1024);
        }
    }
}

#[test]
fn a_single_file_is_always_parsed_and_esm_overrides_its_package_type() {
    let fixture = fixture();
    let legacy = fixture.file("src/legacy.js");
    let (script, _) = report(&["parse", &legacy, "--list"]);
    assert_eq!(script["totals"]["parsed_ok"], 1);
    assert_eq!(script["files"][0]["path"], "legacy.js");
    assert_eq!(script["files"][0]["package_type"], "commonjs");
    let (module, _) = report(&["parse", &legacy, "--list", "--esm"]);
    assert_eq!(module["totals"]["recovered"], 1);
    assert_eq!(module["files"][0]["package_type"], "module");
    assert_eq!(module["diagnostics"][0]["path"], "legacy.js");
    // Without --esm, a file alone follows the package.json above its directory, as in the
    // directory run.
    let (esm, _) = report(&["parse", &fixture.file("esm/legacy.js"), "--list"]);
    assert_eq!(esm["files"][0]["package_type"], "module");
    assert_eq!(esm["totals"]["recovered"], 1);

    // Explicitly named files are parsed whatever their class.
    let (test_file, _) = report(&["parse", &fixture.file("test/app.test.js"), "--list"]);
    assert_eq!(test_file["totals"]["selected"], 1);
    assert_eq!(test_file["files"][0]["class"], "test");
    assert_eq!(test_file["files"][0]["status"], "parsed");
}

#[test]
fn exit_codes_distinguish_usage_and_root_errors() {
    let fixture = fixture();
    let code = |args: &[&str]| jsspector(args).status.code();
    let missing = fixture.file("missing");
    assert_eq!(code(&["parse", &missing]), Some(3), "unreadable root");
    let manifest = fixture.file("package.json");
    assert_eq!(code(&["parse", &manifest]), Some(2), "unsupported file");
    let types = fixture.file("src/types.d.ts");
    assert_eq!(code(&["parse", &types]), Some(2), "declaration file");
    assert_eq!(code(&["parse", fixture.root(), "--esm"]), Some(2));
    assert_eq!(
        code(&["parse", fixture.root(), "--include", "nope"]),
        Some(2)
    );
    assert_eq!(code(&["parse", fixture.root(), "--threads", "0"]), Some(2));
    // Parse failures are diagnostics, not errors.
    assert_eq!(code(&["parse", &fixture.file("src/broken.js")]), Some(0));
}

/// Inputs that used to overflow the parser's stack and abort the whole run (exit 134, no
/// report): nesting the bracket prescan could not see (D2-PLAN-01), and recursion without
/// brackets (D2-PLAN-02). Now each one is either skipped or parsed on a large enough stack.
#[test]
fn inputs_deep_enough_to_overflow_a_worker_stack_never_abort_the_run() {
    let dir = tempfile::tempdir().unwrap();
    let root = dir.path().join("deep");
    let lines = 200_000 / 200;
    write(
        &root,
        "hidden_parens.js",
        format!(
            "var a = 1;\nx =\n{}1{};\n",
            format!("a++ / {}\n", "(".repeat(200)).repeat(lines),
            format!("\n{}", ")".repeat(200)).repeat(lines)
        ),
    );
    write(
        &root,
        "arrows.js",
        format!("f =\n{}1;\n", "a =>\n".repeat(300_000)),
    );
    write(
        &root,
        "assign.js",
        format!("var a;\n{}1;\n", "a =\n".repeat(500_000)),
    );
    write(
        &root,
        "generic.ts",
        format!(
            "type T =\n{}B{};\n",
            "A<\n".repeat(170_000),
            "\n>".repeat(170_000)
        ),
    );
    write(&root, "ok.js", "ok();\n");
    // One thread, so the deep files' stacks are not in use all at once.
    let (report, _) = report(&["parse", root.to_str().unwrap(), "--list", "--threads", "1"]);
    let status = |path: &str| {
        let record = report["files"]
            .as_array()
            .unwrap()
            .iter()
            .find(|f| f["path"] == path)
            .unwrap();
        (
            str_of(record, "status").to_owned(),
            record["reason"].clone(),
        )
    };
    assert_eq!(
        status("hidden_parens.js"),
        ("skipped".to_owned(), json!("too-deep"))
    );
    for parsed in ["arrows.js", "assign.js", "generic.ts", "ok.js"] {
        assert_eq!(
            status(parsed),
            ("parsed".to_owned(), Value::Null),
            "{parsed}"
        );
    }
}
